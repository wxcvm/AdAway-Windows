"""Keep the auditable PowerShell helper and the executable's embedded copy identical."""
from pathlib import Path
import argparse
import json

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
source=(root/'update_portable.ps1').read_text(encoding='utf-8')
text='/* Generated by tools/embed-portable-updater.py; review update_portable.ps1. */\n'
text+='static const wchar_t portable_update_script[] =\n'
text+='\n'.join('    L'+json.dumps(line+'\r\n',ensure_ascii=True) for line in source.splitlines())+';\n'
target=root/'update_portable_script.h'
if args.check:
    if target.read_text(encoding='utf-8')!=text: raise SystemExit('Embedded portable updater differs from reviewed helper')
else: target.write_text(text,encoding='utf-8',newline='\n')
