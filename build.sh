#!/usr/bin/env bash
# Build the standalone Windows x64 ADBlock web server with mingw-w64.
# Run inside an MSYS2 MINGW64 shell (see .github/workflows/windows-release.yml).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
# 本仓库就是 Windows 端仓库：$HERE 即仓库根目录，不要再往上一级跳。
cd "$HERE"

# C 服务端核心（webserver.c / mongoose / cosmetic 等）不在本仓库里，而是由 CI 从 AdAway 仓库
# 的固定提交取出后放在 $HERE/jni（见 .github/workflows/windows-release.yml）。
# 这样做是为了避免把同一份 C 代码复制两份后各自漂移 —— 历史上正是这样分叉的。
# 本地构建时可用环境变量 ADBLOCK_JNI 指向任意一份检出的 webserver/jni。
JNI="${ADBLOCK_JNI:-$HERE/jni}"
if [ ! -f "$JNI/webserver.c" ]; then
  echo "ERROR: 未找到 C 服务端核心：$JNI/webserver.c"
  echo "       本地构建请设置 ADBLOCK_JNI=/path/to/AdAway/webserver/jni"
  exit 1
fi

OUT="$HERE/dist"
CORE_SOURCE="$HERE/.build-core/webserver.c"
bash fetch-transport-contract.sh
bash fetch-tcp-contract.sh
bash fetch-log-contract.sh
python3 tools/build-rule-core.py "$JNI/webserver.c" "$CORE_SOURCE"
rm -rf "$OUT"; mkdir -p "$OUT"
python3 tools/embed-portable-updater.py --check
cp "$HERE/update_portable.ps1" "$OUT/update_portable.ps1"

echo "==> Building pinned official OpenSSL 3.5.9 ..."
bash "$HERE/scripts/build-official-openssl.sh"
SSL_PREFIX="$HERE/.openssl-build/install"

echo "==> Embedding Win11 visual-style manifest + application icon ..."
# The icon is generated by CI (Pillow); embed it when present so a plain
# local build still works.
RC_FILE="$HERE/app.rc"
if [ -f "$HERE/app.ico" ]; then
  # windres resolves resources relative to the .rc file, and it is a native
  # Windows binary: an MSYS-style /d/... path would not be found.
  RC_FILE="$HERE/app_build.rc"
  cat "$HERE/app.rc" > "$RC_FILE"
  printf '\n1 ICON "app.ico"\n' >> "$RC_FILE"
fi
windres "$RC_FILE" -O coff -o "$HERE/app_res.o"

source "$HERE/scripts/gui-sources.sh"

echo "==> Compiling webserver.exe ..."
PREVIEW_CFLAGS=()
if [ "${ADBLOCK_PREVIEW_BUILD:-0}" = 1 ]; then
  PREVIEW_CFLAGS=(-DADBLOCK_PREVIEW_BUILD=1)
elif [ "${ADBLOCK_INPLACE_PREVIEW:-0}" = 1 ]; then
  PREVIEW_CFLAGS=(-DADBLOCK_INPLACE_PREVIEW=1)
fi
[[ "${GITHUB_RUN_ID:-0}" =~ ^[0-9]{1,20}$ ]] || { echo 'Invalid build identity'; exit 1; }
gcc \
  -DADBLOCK_UPDATE_BUILD=\"${GITHUB_RUN_ID:-0}\" \
  "${PREVIEW_CFLAGS[@]}" \
  -std=c11 -O2 -Wall -mwindows \
  -fstack-protector-strong \
  -Wl,--dynamicbase,--nxcompat,--high-entropy-va \
  -D MG_ENABLE_IPV6 -DMG_TLS=MG_TLS_OPENSSL -DMG_ENABLE_POLL=1 \
  -I"$HERE" \
  -I"$JNI" \
  -I"$HERE/shared-contract" \
  -I"$HERE/transport-contract" \
  -I"$HERE/tcp-contract" \
  -I"$HERE/log-contract" \
  -I"$SSL_PREFIX/include" \
  -I"$MINGW_PREFIX/include" \
  -o "$OUT/webserver.exe" \
  "$CORE_SOURCE" "$JNI/mongoose/mongoose.c" "${GUI_SOURCES[@]}" \
  "$HERE/app_res.o" \
  "$SSL_PREFIX/lib/libssl.a" "$SSL_PREFIX/lib/libcrypto.a" \
  -lws2_32 -lwinmm -lpthread \
  -lgdi32 -luser32 -lcomdlg32 -lshell32 -ladvapi32 -lcrypt32 -liphlpapi \
  -ldwmapi -luxtheme -lpsapi -lwinhttp -lbcrypt -lwintrust

echo "==> Bundling runtime DLLs ..."
for dll in zlib-1.dll \
           libgcc_s_seh-1.dll libwinpthread-1.dll libssp-0.dll; do
  if [ -f "$MINGW_PREFIX/bin/$dll" ]; then
    cp "$MINGW_PREFIX/bin/$dll" "$OUT/"
  fi
done

# Refuse to publish a binary with a dependency that is not bundled and not a
# Windows system DLL. -fstack-protector-strong adds libssp, and a missing DLL
# is invisible on a CI runner (MSYS2's bin is on PATH there) but makes the
# executable fail to start on a user's machine.
echo "==> Verifying runtime dependencies ..."
missing=""
for dll in $(objdump -p "$OUT/webserver.exe" | sed -n 's/^[[:space:]]*DLL Name:[[:space:]]*//p'); do
  [ -f "$OUT/$dll" ] && continue
  [ -f "/c/Windows/System32/$dll" ] && continue
  missing="$missing $dll"
done
if [ -n "$missing" ]; then
  echo "ERROR: webserver.exe needs DLLs that are neither bundled nor system:"
  echo "      $missing"
  exit 1
fi
# Never ship or load a mismatched runtime OpenSSL DLL.
if objdump -p "$OUT/webserver.exe" | grep -Eiq 'DLL Name: *(libssl|libcrypto)'; then
  echo "ERROR: dynamic OpenSSL import remained" >&2
  exit 1
fi
if ! strings "$OUT/webserver.exe" | grep -F 'OpenSSL 3.5.9' >/dev/null; then
  echo "ERROR: official OpenSSL 3.5.9 signature absent" >&2
  exit 1
fi
echo "==> All imports satisfied ($(objdump -p "$OUT/webserver.exe" | grep -c 'DLL Name:'))"

echo "==> Build output:"
ls -la "$OUT"
echo "==> Done."
